/// 一次入库意图的结果 (成功 = 元数据已进 core 且 lua 已落盘).
#[derive(Debug, Clone)]
pub struct AddToLibraryOutcome {
    pub app_id: AppId,
    pub provider_id: String,
    pub provider_trace: Vec<CatalogTraceEntry>,
    pub lua_path: PathBuf,
    pub epoch: u64,
    pub owned_count: usize,
    /// 入库成功后仍缺的下载数据 (有清单但缺 key/token), 空 = 齐全.
    pub missing: MissingDownloadData,
    /// 写入 depotcache 的原始 .manifest 文件数 (0 = 源没给字节, 不失败).
    pub manifest_files_written: usize,
    /// 本次并入的 DLC (仅解锁 / 可下载); 关 auto_dlc 时为空.
    pub dlc: DlcExpandReport,
    /// 最终 bundle 里全部 owned app (主 + DLC), 供 package0 注入.
    pub owned_apps: Vec<AppId>,
}

/// 下载数据缺失情况 (Steam 拿不到就下不了, 应该提示用户).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct MissingDownloadData {
    /// 只有清单 (manifest) 没拿到下载密钥 (depot key) 的 depot, 升序.
    pub depot_keys: Vec<DepotId>,
    /// 有清单但缺 access token (下载 0B 的常见原因).
    pub access_token: bool,
}

impl MissingDownloadData {
    /// 全部数据齐了, 不需要提示.
    pub fn is_empty(&self) -> bool {
        self.depot_keys.is_empty() && !self.access_token
    }

    /// 人类可读的缺失描述, 空串 = 齐全.
    pub fn describe(&self) -> String {
        let mut parts = Vec::new();
        if !self.depot_keys.is_empty() {
            let ids: Vec<String> = self.depot_keys.iter().map(u32::to_string).collect();
            parts.push(format!("下载密钥 (Depot {})", ids.join(", ")));
        }
        if self.access_token {
            parts.push("访问令牌".to_owned());
        }
        parts.join("、")
    }
}

/// 算 bundle 里缺的下载数据 (只算请求 app 的).
///
/// 判定:
/// - depot key: 该 depot 声明了 manifest (能告诉 Steam 下哪个清单), 但没有 depot key
///   (解密需要). 只有 manifest 没有 key 时 Steam 拿不到解密钥匙, 下载会失败.
/// - access token: 有清单但没给 token, Steam 下载授权过不去 (常见表现为下载 0B).
pub fn missing_download_data(app_id: AppId, bundle: &CatalogBundle) -> MissingDownloadData {
    let app_depots = bundle.app_depots.get(&app_id);
    let mut depot_keys: Vec<DepotId> = app_depots
        .into_iter()
        .flatten()
        .copied()
        .filter(|depot_id| {
            bundle.manifests.contains_key(depot_id) && !bundle.depot_keys.contains_key(depot_id)
        })
        .collect();
    depot_keys.sort_unstable();
    let has_manifest = app_depots
        .into_iter()
        .flatten()
        .any(|depot_id| bundle.manifests.contains_key(depot_id));
    // 源明确说不需要 token (steamcmd `_missing_token: false`) 时不报缺 token.
    let need_token = bundle.requires_token != Some(false);
    MissingDownloadData {
        depot_keys,
        // token 为 0 等于没有 (上游用 0 表示未收录).
        access_token: has_manifest
            && need_token
            && bundle.access_tokens.get(&app_id).copied().unwrap_or(0) == 0,
    }
}

/// 将 bundle 写成兼容上游的 lua 片段.
pub fn format_catalog_lua(app_id: AppId, bundle: &CatalogBundle) -> String {
    let mut out = String::from("-- generated by SteamTools catalog_add\n");
    let mut apps = bundle.apps.clone();
    apps.sort_unstable();
    apps.dedup();
    for id in apps {
        let purchase_time = bundle.purchase_times.get(&id).copied().unwrap_or(0);
        out.push_str(&format!("addappid({id}, {purchase_time})\n"));
    }

    let mut depots: Vec<_> = bundle.app_depots.values().flatten().copied().collect();
    depots.sort_unstable();
    depots.dedup();
    for depot_id in depots {
        let key = bundle
            .depot_keys
            .get(&depot_id)
            .map(String::as_str)
            .unwrap_or_default();
        out.push_str(&format!("addappid({depot_id}, 0, \"{key}\")\n"));
    }
    let mut access_tokens: Vec<_> = bundle.access_tokens.iter().collect();
    access_tokens.sort_unstable_by_key(|(app_id, _)| **app_id);
    for (&id, &token) in access_tokens {
        out.push_str(&format!("addtoken({id}, \"{token}\")\n"));
    }
    let mut manifests: Vec<_> = bundle.manifests.iter().collect();
    manifests.sort_unstable_by_key(|(depot_id, _)| **depot_id);
    for (&depot, over) in manifests {
        // 第三参 size 必须写出: 否则 hook 侧 size=0, 安装对话框显示 0B
        // (OpenSteamTool: setManifestid(depot, gid, size); size 默认 0 会保留原值,
        // 但假 license 路径原值常是 0, 必须把 steamcmd download/size 灌进去).
        if over.size != 0 {
            out.push_str(&format!(
                "setmanifestid({depot}, \"{}\", {})\n",
                over.manifest_gid, over.size
            ));
        } else {
            out.push_str(&format!(
                "setmanifestid({depot}, \"{}\")\n",
                over.manifest_gid
            ));
        }
    }
    let mut app_depots: Vec<_> = bundle.app_depots.iter().collect();
    app_depots.sort_unstable_by_key(|(id, _)| **id);
    for (&id, depots) in app_depots {
        let mut depots = depots.clone();
        depots.sort_unstable();
        depots.dedup();
        let values = depots
            .iter()
            .map(u32::to_string)
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!(
            "if type(setappdepots) == \"function\" then setappdepots({id}, {{{values}}}) end\n"
        ));
    }
    debug_assert!(bundle.apps.contains(&app_id));
    out
}

pub fn catalog_lua_path(steam_root: &Path, app_id: AppId) -> PathBuf {
    default_lua_dir(steam_root).join(format!("stt_{app_id}.lua"))
}

/// 写入 `<Steam>/config/lua/stt_{app_id}.lua`.
pub fn write_catalog_lua(
    steam_root: &Path,
    app_id: AppId,
    bundle: &CatalogBundle,
) -> Result<PathBuf> {
    let dir = default_lua_dir(steam_root);
    std::fs::create_dir_all(&dir).map_err(|source| ConfigError::Io {
        path: dir.clone(),
        source,
    })?;
    let path = catalog_lua_path(steam_root, app_id);
    let body = format_catalog_lua(app_id, bundle);
    crate::intent::write_atomic(&path, &body)?;
    Ok(path)
}

/// 原始 .manifest 文件名: `{depot}_{gid}.manifest` (Fluent / Steam 约定).
pub fn manifest_file_name(depot_id: DepotId, manifest_gid: u64) -> String {
    format!("{depot_id}_{manifest_gid}.manifest")
}

/// 把 archive 给的原始 .manifest 写到两个 depotcache 目录.
///
/// 对齐 Fluent-Install:
/// - `<Steam>/depotcache/{depot}_{gid}.manifest`
/// - `<Steam>/config/depotcache/{depot}_{gid}.manifest`
///
/// 缺 blob 不报错 (request-code hook 仍可在线拉); 单文件写失败计入 0 次成功.
pub fn write_manifest_blobs(
    steam_root: &Path,
    blobs: &[stt_catalog::ManifestBlob],
) -> Result<usize> {
    if blobs.is_empty() {
        return Ok(0);
    }
    let primary = steam_root.join("depotcache");
    let secondary = steam_root.join("config").join("depotcache");
    for dir in [&primary, &secondary] {
        std::fs::create_dir_all(dir).map_err(|source| ConfigError::Io {
            path: dir.clone(),
            source,
        })?;
    }
    let mut written = 0usize;
    for blob in blobs {
        if blob.bytes.is_empty() || blob.depot_id == 0 || blob.manifest_gid == 0 {
            continue;
        }
        let name = manifest_file_name(blob.depot_id, blob.manifest_gid);
        let mut ok_any = false;
        for dir in [&primary, &secondary] {
            let path = dir.join(&name);
            match write_atomic_bytes(&path, &blob.bytes) {
                Ok(()) => ok_any = true,
                Err(_) => {
                    // 单个目录失败不阻断另一目录 / 其它 depot.
                }
            }
        }
        if ok_any {
            written += 1;
        }
    }
    Ok(written)
}

fn write_atomic_bytes(path: &Path, bytes: &[u8]) -> Result<()> {
    use std::ffi::OsString;
    let mut name: OsString = path.file_name().unwrap_or_default().to_owned();
    name.push(".tmp");
    let tmp = path.with_file_name(name);
    std::fs::write(&tmp, bytes).map_err(|source| ConfigError::Io {
        path: tmp.clone(),
        source,
    })?;
    std::fs::rename(&tmp, path).map_err(|source| {
        let _ = std::fs::remove_file(&tmp);
        ConfigError::Io {
            path: path.to_path_buf(),
            source,
        }
    })
}

fn now_unix() -> u32 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .ok()
        .and_then(|d| u32::try_from(d.as_secs()).ok())
        .unwrap_or(0)
}

/// 工具开启时: fetch → (可选 DLC 扩展) → 写 lua → 合并进 ConfigState.
pub fn add_to_library(
    state: &ConfigState,
    steam_root: &Path,
    provider: &dyn CatalogProvider,
    app_id: AppId,
) -> Result<AddToLibraryOutcome> {
    add_to_library_with_dlc(
        state,
        steam_root,
        provider,
        app_id,
        DlcExpandOptions::disabled(),
        WinHttpGetOptions::default(),
    )
}

/// 同 [`add_to_library`], 带 DLC 扩展选项.
pub fn add_to_library_with_dlc(
    state: &ConfigState,
    steam_root: &Path,
    provider: &dyn CatalogProvider,
    app_id: AppId,
    dlc_opts: DlcExpandOptions,
    http: WinHttpGetOptions,
) -> Result<AddToLibraryOutcome> {
    if !state.tools().is_enabled(ToolId::CatalogAdd) {
        return Err(ConfigError::Invalid("catalog_add tool is disabled".into()));
    }

    let fetched = provider.fetch_with_trace(app_id)?;
    let mut bundle = validate_bundle(app_id, fetched.bundle)?;
    let purchase = now_unix();
    bundle.purchase_times.entry(app_id).or_insert(purchase);

    let dlc = expand_dlcs(
        app_id,
        &mut bundle,
        &fetched.related_dlc_ids,
        provider,
        dlc_opts,
        http,
    );
    // 扩展后可能多了 apps/depots, 再校验一次.
    let bundle = validate_bundle(app_id, bundle)?;

    let lua_path = write_catalog_lua(steam_root, app_id, &bundle)?;
    // Fluent 路径: 有原始 .manifest 就写 depotcache; 没有也不挡入库.
    let manifest_files_written =
        write_manifest_blobs(steam_root, &fetched.manifest_blobs).unwrap_or(0);

    // 以磁盘 lua 为准重载, 避免 DLC 列表缩小时 merge 残留旧 owned.
    #[cfg(feature = "lua")]
    {
        let _ = state.reload_lua_dirs(steam_root);
    }
    #[cfg(not(feature = "lua"))]
    {
        state.with_rules_mut(|rules| {
            rules.apply_catalog_bundle(&bundle);
        });
    }

    let mut owned_apps: Vec<AppId> = bundle.apps.iter().copied().filter(|&id| id != 0).collect();
    owned_apps.sort_unstable();
    owned_apps.dedup();

    Ok(AddToLibraryOutcome {
        app_id,
        provider_id: fetched.source,
        provider_trace: fetched.trace,
        lua_path,
        epoch: state.rules_epoch(),
        owned_count: state.owned_count(),
        missing: missing_download_data(app_id, &bundle),
        manifest_files_written,
        dlc,
        owned_apps,
    })
}

/// 一次移除的结果.
#[derive(Debug, Clone)]
pub struct RemoveFromLibraryOutcome {
    pub app_id: AppId,
    /// 删掉的 lua; 文件本来就不在时为 `None` (仍算成功).
    pub lua_path: Option<PathBuf>,
    pub epoch: u64,
    pub owned_count: usize,
}

/// 把入库撤掉: 删 `stt_{app_id}.lua`, 然后整表重扫.
///
/// 不去 `AppRules` 里做减法 —— 那份状态是所有 lua 合并出来的, 单独摘一个 app 容易
/// 与磁盘不一致. 删完重扫是唯一能保证两边一致的做法, 而且几十个文件也就几毫秒.
///
/// 只删我们自己写的那个文件; 用户手写的 lua 一概不碰.
#[cfg(feature = "lua")]
pub fn remove_from_library(
    state: &ConfigState,
    steam_root: &Path,
    app_id: AppId,
) -> Result<RemoveFromLibraryOutcome> {
    let path = catalog_lua_path(steam_root, app_id);
    let lua_path = match std::fs::remove_file(&path) {
        Ok(()) => Some(path),
        // 已经不在了: 目的已经达到, 不当错误.
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(source) => {
            return Err(ConfigError::Io {
                path: path.clone(),
                source,
            })
        }
    };
    state.reload_lua_dirs(steam_root);
    Ok(RemoveFromLibraryOutcome {
        app_id,
        lua_path,
        epoch: state.rules_epoch(),
        owned_count: state.owned_count(),
    })
}

